import fs from "node:fs";
import path from "node:path";
import type { LedgerDb } from "@fluffles/storage";
import type { MemoryPaths } from "./paths";
import { readFileIfExists } from "./notes";
import { backlinksFor, listDocuments, resolveTitle, type Backlink } from "./index/search";

/** Resolve a caller-supplied relative path, refusing anything outside the memory root. */
function containedPath(root: string, relPath: string): string | null {
  if (path.isAbsolute(relPath)) return null;
  const resolved = path.resolve(root, relPath);
  const rootResolved = path.resolve(root);
  if (resolved !== rootResolved && !resolved.startsWith(rootResolved + path.sep)) return null;
  return resolved;
}

export interface WikiPage {
  path: string;
  title: string;
  content: string;
  backlinks: Backlink[];
}

/**
 * Exact retrieval. A path returns the file; a wiki title or alias returns the
 * page plus its backlinks. Line bounds are 1-based and inclusive.
 */
export function getMemoryDocument(
  db: LedgerDb,
  paths: MemoryPaths,
  pathOrTitle: string,
  lineStart?: number,
  lineEnd?: number
): WikiPage | null {
  let relPath = pathOrTitle;
  let title = pathOrTitle;
  let resolvedWiki = false;
  const absoluteCandidate = containedPath(paths.root, pathOrTitle);
  if (absoluteCandidate == null || !fs.existsSync(absoluteCandidate)) {
    const resolved = resolveTitle(db, pathOrTitle);
    if (!resolved) return null;
    relPath = resolved.path;
    title = resolved.title;
    resolvedWiki = true;
  }
  const absolutePath = containedPath(paths.root, relPath);
  if (absolutePath == null) return null;
  const content = readFileIfExists(absolutePath);
  if (content == null) return null;
  let body = content;
  if (lineStart != null) {
    const lines = content.split("\n");
    const start = Math.max(1, lineStart);
    const end = lineEnd != null ? Math.min(lines.length, lineEnd) : lines.length;
    body = lines.slice(start - 1, end).join("\n");
  }
  const isWiki = resolvedWiki || relPath.startsWith("wiki/");
  return {
    path: relPath,
    title,
    content: body,
    backlinks: isWiki ? backlinksFor(db, relPath) : []
  };
}

/**
 * `wiki/index.md` is a generated catalog of every page, grouped by tag. Not
 * injected; it is the entry point when the agent does not know what it is
 * looking for.
 */
export function generateWikiIndex(db: LedgerDb, paths: MemoryPaths, now: Date = new Date()): string {
  const pages = listDocuments(db, "wiki");
  const byTag = new Map<string, { path: string; title: string }[]>();
  for (const page of pages) {
    const tags = page.tags.tags ?? [];
    const groups = tags.length ? tags : ["untagged"];
    for (const tag of groups) {
      (byTag.get(tag) ?? byTag.set(tag, []).get(tag)!).push({ path: page.path, title: page.title });
    }
  }
  const lines: string[] = [
    "# wiki index",
    "",
    `Generated by \`memory index\` at ${now.toISOString()}. Do not edit by hand.`,
    ""
  ];
  for (const tag of [...byTag.keys()].sort()) {
    lines.push(`## ${tag}`, "");
    for (const page of byTag.get(tag)!.sort((a, b) => a.title.localeCompare(b.title))) {
      lines.push(`- [[${page.title}]] (${page.path})`);
    }
    lines.push("");
  }
  if (!pages.length) lines.push("No pages yet. The wiki fills from daily notes as work happens.", "");
  const content = lines.join("\n");
  fs.mkdirSync(paths.wikiDir, { recursive: true });
  fs.writeFileSync(paths.wikiIndexFile, content);
  return content;
}
